# Generates bibliography.bib from Zotero (Better BibTeX local export): keeps only the fields ISO 690
# needs, in a fixed order, and validates the result. bibliography.bib is committed, so the thesis builds
# without Zotero; run this only when the library changed.
#   powershell -ExecutionPolicy Bypass -File scripts\bib.ps1 [-Url <export url>] [-Check]
param(
    [string]$Url = 'http://127.0.0.1:23119/better-bibtex/export/library?/1/library.bibtex',
    [switch]$Check   # only validate the existing bibliography.bib, do not fetch
)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'bibliography.bib'
$buildDir = Join-Path $root 'build'
$raw = Join-Path $buildDir 'bibliography.raw.bib'

# Field order inside a record (ISO 690: author, title, container, publisher, year, volume, pages, doi/url).
$order = 'author', 'editor', 'title', 'booktitle', 'journal', 'publisher', 'school', 'institution', 'address',
         'edition', 'series', 'year', 'month', 'volume', 'number', 'pages', 'eid', 'doi', 'url', 'urldate', 'howpublished', 'note'
$webTypes = 'online', 'misc', 'electronic', 'www'

function Get-Entries([string]$text) {
    # yields @{Type; Key; Fields = ordered hashtable}; handles nested braces
    $i = 0
    while (($i = $text.IndexOf('@', $i)) -ge 0) {
        $m = [regex]::Match($text.Substring($i), '^@(\w+)\s*\{\s*([^,\s]+)\s*,')
        if (-not $m.Success) { $i++; continue }
        $start = $i + $m.Length; $depth = 1; $j = $i + $m.Value.IndexOf('{') + 1
        while ($j -lt $text.Length -and $depth -gt 0) {
            $c = $text[$j]
            if ($c -eq '{') { $depth++ } elseif ($c -eq '}') { $depth-- }
            $j++
        }
        $body = $text.Substring($start, $j - 1 - $start)
        $fields = [ordered]@{}
        $k = 0
        while ($k -lt $body.Length) {
            $fm = [regex]::Match($body.Substring($k), '^\s*(\w+)\s*=\s*')
            if (-not $fm.Success) { $k++; continue }
            $k += $fm.Length
            if ($k -ge $body.Length) { break }
            if ($body[$k] -eq '{') {
                $d = 0; $v0 = $k
                do { if ($body[$k] -eq '{') { $d++ } elseif ($body[$k] -eq '}') { $d-- }; $k++ } while ($k -lt $body.Length -and $d -gt 0)
                $val = $body.Substring($v0 + 1, $k - $v0 - 2)
            } elseif ($body[$k] -eq '"') {
                $v0 = ++$k
                while ($k -lt $body.Length -and $body[$k] -ne '"') { $k++ }
                $val = $body.Substring($v0, $k - $v0); $k++
            } else {
                $v0 = $k
                while ($k -lt $body.Length -and $body[$k] -ne ',') { $k++ }
                $val = $body.Substring($v0, $k - $v0).Trim()
            }
            $fields[$fm.Groups[1].Value.ToLower()] = $val.Trim()
        }
        [pscustomobject]@{ Type = $m.Groups[1].Value.ToLower(); Key = $m.Groups[2].Value; Fields = $fields }
        $i = $j
    }
}

if (-not $Check) {
    New-Item -ItemType Directory -Force $buildDir | Out-Null
    # curl.exe: Invoke-WebRequest gets its connection closed by the Zotero endpoint.
    & curl.exe -s -S -f --max-time 120 -o $raw $Url
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path $raw) -or (Get-Item $raw).Length -lt 100) {
        if (Test-Path $out) { Write-Warning "Zotero not reachable (curl exit $LASTEXITCODE) - keeping existing bibliography.bib"; exit 0 }
        throw 'Zotero not reachable and there is no bibliography.bib yet. Start Zotero (Better BibTeX) and rerun.'
    }
    $entries = @(Get-Entries ([IO.File]::ReadAllText($raw, [Text.Encoding]::UTF8)))
    $sb = New-Object Text.StringBuilder
    [void]$sb.AppendLine('% Generated by scripts/bib.ps1 from Zotero (Better BibTeX). Do not edit by hand.')
    foreach ($e in $entries) {
        $f = $e.Fields
        if ($f.Contains('doi') -and $webTypes -notcontains $e.Type) { $f.Remove('url'); $f.Remove('urldate') }   # DOI is enough for papers
        if ($f.Contains('doi')) { $f.Remove('url') }
        [void]$sb.AppendLine()
        [void]$sb.AppendLine("@$($e.Type){$($e.Key),")
        foreach ($name in $order) { if ($f.Contains($name) -and $f[$name]) { [void]$sb.AppendLine("  $name = {$($f[$name])},") } }
        [void]$sb.AppendLine('}')
    }
    [IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
    Write-Host "bibliography.bib: $($entries.Count) entries from Zotero"
}

# Validation (always)
$all = @(Get-Entries ([IO.File]::ReadAllText($out, [Text.Encoding]::UTF8)))
$dups = $all | Group-Object Key | Where-Object Count -gt 1
foreach ($d in $dups) { Write-Warning "duplicate key: $($d.Name)" }
$bad = 0
foreach ($e in $all) {
    $missing = @('author', 'title', 'year') | Where-Object { -not $e.Fields.Contains($_) -and -not ($_ -eq 'author' -and $e.Fields.Contains('editor')) }
    if ($missing) { Write-Warning "$($e.Key): missing $($missing -join ', ')"; $bad++ }
}
Write-Host "checked $($all.Count) entries: $bad with missing fields, $(@($dups).Count) duplicate keys"
